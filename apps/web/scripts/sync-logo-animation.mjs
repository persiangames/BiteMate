import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const SOURCE = path.join(ROOT, 'brand/logo animation.mp4');
const DEST = path.join(ROOT, 'apps/web/public/brand/logo-animation.mp4');
const ALPHA_DEST = path.join(ROOT, 'apps/web/public/brand/logo-animation-alpha.webm');
const VERSION_FILE = path.join(
  ROOT,
  'apps/web/src/presentation/components/brand/logo-animation.version.ts',
);

if (!fs.existsSync(SOURCE)) {
  console.error(`Missing source animation: ${SOURCE}`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(DEST), { recursive: true });
fs.copyFileSync(SOURCE, DEST);

function getFfmpegPath() {
  try {
    return execSync('python -c "import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())"', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function buildAlphaWebm(ffmpegPath) {
  const vf =
    "format=rgba,geq=r='r(X,Y)':g='g(X,Y)':b='b(X,Y)':a='if(lte(abs(r(X,Y)-244)+abs(g(X,Y)-235)+abs(b(X,Y)-215),48),0,255)',format=yuva420p";
  const result = spawnSync(
    ffmpegPath,
    ['-y', '-i', DEST, '-vf', vf, '-c:v', 'libvpx-vp9', '-pix_fmt', 'yuva420p', '-auto-alt-ref', '0', '-an', ALPHA_DEST],
    { stdio: 'inherit' },
  );
  return result.status === 0 && fs.existsSync(ALPHA_DEST);
}

const ffmpegPath = getFfmpegPath();
let alphaBuilt = false;
if (ffmpegPath) {
  alphaBuilt = buildAlphaWebm(ffmpegPath);
  if (alphaBuilt) {
    console.log('Generated logo animation alpha → public/brand/logo-animation-alpha.webm');
  } else {
    console.warn('Alpha WebM generation failed; intro will use MP4 with blend fallback.');
  }
} else {
  console.warn('ffmpeg not found; skipping alpha WebM generation.');
}

const hash = crypto.createHash('md5');
hash.update(fs.readFileSync(DEST));
if (alphaBuilt) {
  hash.update(fs.readFileSync(ALPHA_DEST));
}
const version = hash.digest('hex').slice(0, 12);

fs.writeFileSync(
  VERSION_FILE,
  `/** Auto-generated by scripts/sync-logo-animation.mjs — do not edit */\nexport const LOGO_ANIMATION_VERSION = '${version}';\n`,
  'utf8',
);

console.log(`Synced logo animation → public/brand/logo-animation.mp4 (${version})`);
