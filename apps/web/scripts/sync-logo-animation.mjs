import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const SOURCE_4K = path.join(ROOT, 'apps/web/public/brand/logo-animation-4k.mp4');
const SOURCE_LEGACY = path.join(ROOT, 'brand/logo animation.mp4');
const SOURCE = fs.existsSync(SOURCE_4K) ? SOURCE_4K : SOURCE_LEGACY;
const DEST = path.join(ROOT, 'apps/web/public/brand/logo-animation.mp4');
const ALPHA_DEST = path.join(ROOT, 'apps/web/public/brand/logo-animation-alpha.webm');
const VERSION_FILE = path.join(
  ROOT,
  'apps/web/src/presentation/components/brand/logo-animation.version.ts',
);

if (!fs.existsSync(SOURCE)) {
  console.error(`Missing source animation: ${SOURCE}`);
  process.exit(1);
}

function getFfmpegPath() {
  try {
    return execSync('python -c "import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())"', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function hashFile(filePath) {
  return crypto.createHash('md5').update(fs.readFileSync(filePath)).digest('hex');
}

function writeVersion(version) {
  fs.writeFileSync(
    VERSION_FILE,
    `/** Auto-generated by scripts/sync-logo-animation.mjs — do not edit */\nexport const LOGO_ANIMATION_VERSION = '${version}';\n`,
    'utf8',
  );
}

const sourceHash = hashFile(SOURCE);
const recipe = 'vp9-alpha-1920-crf20-chromakey-f3ebda';
const expectedVersion = crypto.createHash('md5').update(sourceHash + recipe).digest('hex').slice(0, 12);

if (
  fs.existsSync(ALPHA_DEST) &&
  fs.existsSync(VERSION_FILE) &&
  fs.readFileSync(VERSION_FILE, 'utf8').includes(expectedVersion)
) {
  console.log(`Logo animation already current (${expectedVersion}) — skip ffmpeg.`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(DEST), { recursive: true });

function buildAlphaWebm(ffmpegPath) {
  // Tight cream-key so 3D round character heads stay intact; 1920 keeps cinematic detail without a 4K decode tax.
  const vf = [
    'scale=1920:-2:flags=lanczos',
    'chromakey=0xF3EBDA:0.08:0.04',
    'format=yuva420p',
  ].join(',');
  const result = spawnSync(
    ffmpegPath,
    [
      '-y',
      '-i',
      SOURCE,
      '-vf',
      vf,
      '-c:v',
      'libvpx-vp9',
      '-pix_fmt',
      'yuva420p',
      '-crf',
      '20',
      '-b:v',
      '0',
      '-row-mt',
      '1',
      '-deadline',
      'good',
      '-cpu-used',
      '2',
      '-auto-alt-ref',
      '0',
      '-an',
      ALPHA_DEST,
    ],
    { stdio: 'inherit' },
  );
  return result.status === 0 && fs.existsSync(ALPHA_DEST);
}

function buildMp4Fallback(ffmpegPath) {
  const result = spawnSync(
    ffmpegPath,
    [
      '-y',
      '-i',
      SOURCE,
      '-vf',
      'scale=1920:-2:flags=lanczos',
      '-c:v',
      'libx264',
      '-crf',
      '18',
      '-preset',
      'fast',
      '-pix_fmt',
      'yuv420p',
      '-an',
      '-movflags',
      '+faststart',
      DEST,
    ],
    { stdio: 'inherit' },
  );
  return result.status === 0;
}

const ffmpegPath = getFfmpegPath();
if (!ffmpegPath) {
  console.warn('ffmpeg not found; skipping logo transcode.');
  writeVersion(expectedVersion);
  process.exit(0);
}

const alphaBuilt = buildAlphaWebm(ffmpegPath);
if (alphaBuilt) {
  console.log('Generated high-quality logo alpha → public/brand/logo-animation-alpha.webm');
} else {
  console.warn('Alpha WebM generation failed; intro will use MP4 fallback.');
}

buildMp4Fallback(ffmpegPath);
writeVersion(expectedVersion);
console.log(`Synced logo animation from ${path.basename(SOURCE)} (${expectedVersion})`);
