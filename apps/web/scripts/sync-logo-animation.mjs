import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const SOURCE = path.join(ROOT, 'brand/logo animation.mp4');
const DEST = path.join(ROOT, 'apps/web/public/brand/logo-animation.mp4');
const VERSION_FILE = path.join(
  ROOT,
  'apps/web/src/presentation/components/brand/logo-animation.version.ts',
);

if (!fs.existsSync(SOURCE)) {
  console.error(`Missing source animation: ${SOURCE}`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(DEST), { recursive: true });
fs.copyFileSync(SOURCE, DEST);

const hash = crypto.createHash('md5').update(fs.readFileSync(DEST)).digest('hex').slice(0, 12);

fs.writeFileSync(
  VERSION_FILE,
  `/** Auto-generated by scripts/sync-logo-animation.mjs — do not edit */\nexport const LOGO_ANIMATION_VERSION = '${hash}';\n`,
  'utf8',
);

console.log(`Synced logo animation → public/brand/logo-animation.mp4 (${hash})`);
