export function readRecentStickers(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_STICKERS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((item): item is string => typeof item === 'string').slice(0, RECENT_STICKERS_LIMIT);
  } catch {
    return [];
  }
}

export function rememberSticker(sticker: string): void {
  const trimmed = sticker.trim();
  if (!trimmed) return;
  const next = [trimmed, ...readRecentStickers().filter((item) => item !== trimmed)].slice(
    0,
    RECENT_STICKERS_LIMIT,
  );
  localStorage.setItem(RECENT_STICKERS_KEY, JSON.stringify(next));
}

export function stickersForCategory(categoryId: StickerCategoryId): readonly string[] {
  if (categoryId === 'RECENT') {
    return readRecentStickers();
  }
  return STICKER_CATEGORIES.find((category) => category.id === categoryId)?.stickers ?? [];
}
